#include <stddef.h>

int	memcmp(const void *s1, const void *s2, size_t n)
{
	size_t	i;

	i = 0;
	if (n == 0)
		return (0);
	while (*((char *)(s1)) == *((char *)(s2)) && i < n)
	{
		s1++;
		s2++;
	}
	return (*((char *)(s1)) - *((char *)(s2)));
}
