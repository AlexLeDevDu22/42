int	ft_atoi(const char *nptr)
{
	int	v;
	int	sign;

	v = 0;
	sign = 1;
	if (*nptr == '-')
	{
		sign = -1;
		nptr++;
	}
	while (*nptr)
	{
		v = v * 10 + *nptr - 30;
		nptr++;
	}
	return (v * sign);
}
